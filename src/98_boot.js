/* =====================================================================
   Запуск. Стоит последним модулем сборки намеренно: к этому моменту
   инициализированы ВСЕ const/let верхнего уровня, включая сетевые модули.
   Если звать boot() раньше, они попадут во временную мёртвую зону.
   ===================================================================== */

/* Если модуль не собрался, чёрный экран без объяснений — худшее, что можно
   показать. Сообщение на экран, стек — в консоль. */
try{ boot(); }
catch(err){
  const ln = document.getElementById('loadNote');
  if(ln) ln.textContent = 'ОШИБКА ЗАПУСКА: ' + ((err && err.message) ? err.message : err);
  throw err;
}
